//! Recognize injected agent-credit footers in prose without treating quoted examples as credits.

/// CommonMark fenced code blocks open with at least three matching backticks or tildes.
#[derive(Default)]
pub struct Fence(Option<(char, usize)>);

impl Fence {
    /// Track opening/closing delimiters. Returns true for a delimiter or a line inside the fence.
    pub fn code_line(&mut self, line: &str) -> bool {
        let stripped = line.trim_start_matches(' ');
        let spaces = line.len() - stripped.len();
        if spaces <= 3
            && let Some(symbol @ ('`' | '~')) = stripped.chars().next()
        {
            let length = stripped.chars().take_while(|&c| c == symbol).count();
            let rest = &stripped[length..];
            if let Some((open, size)) = self.0 {
                if symbol == open && length >= size && rest.trim().is_empty() {
                    self.0 = None;
                }
                return true;
            }
            if length >= 3 && (symbol != '`' || !rest.contains('`')) {
                self.0 = Some((symbol, length));
                return true;
            }
        }
        self.0.is_some()
    }

    /// An unmatched opening fence would expose a Markdown footer as literal code.
    pub fn is_open(&self) -> bool {
        self.0.is_some()
    }
}

/// True when a final prose paragraph contains a recognizable agent-credit line.
/// Quotes, fenced examples, indented code, and a human co-author's vendor email are ignored.
pub fn has_harness_footer(text: &str) -> bool {
    let mut fence = Fence::default();
    let mut matches = false;
    for line in text.trim_end().lines() {
        let code = fence.code_line(line);
        let content = line.trim();
        if content.is_empty() {
            matches = false;
            continue;
        }
        if code || line.starts_with("    ") || line.starts_with('\t') || content.starts_with('>') {
            continue;
        }
        let normalized = content.trim_start_matches('🤖').trim_start().to_lowercase();
        let credit = [
            "generated with ",
            "generated by ",
            "made with ",
            "co-authored-by:",
        ]
        .into_iter()
        .find_map(|prefix| normalized.strip_prefix(prefix));
        if let Some(value) = credit {
            let name = value
                .trim_start()
                .trim_start_matches('[')
                .split([']', '<'])
                .next()
                .unwrap_or_default()
                .trim();
            matches |= is_tool_name(name);
        } else if let Some((name, address)) = normalized
            .strip_prefix('[')
            .and_then(|link| link.strip_suffix(')'))
            .and_then(|link| link.split_once("](https://"))
        {
            let host = address.split('/').next().unwrap_or_default();
            matches |= is_tool_name(name)
                && matches!(
                    host,
                    "claude.com"
                        | "claude.ai"
                        | "cursor.com"
                        | "openai.com"
                        | "developers.openai.com"
                        | "github.com"
                        | "geminicli.com"
                        | "antigravity.google"
                        | "devin.ai"
                );
        }
    }
    matches
}

fn is_tool_name(name: &str) -> bool {
    matches!(
        name,
        "claude"
            | "claude code"
            | "codex"
            | "openai codex"
            | "chatgpt"
            | "cursor"
            | "cursor agent"
            | "github copilot"
            | "copilot"
            | "gemini"
            | "gemini cli"
            | "antigravity"
            | "devin"
            | "devin ai"
    ) || ["claude opus ", "claude sonnet ", "claude haiku "]
        .iter()
        .any(|prefix| name.starts_with(prefix))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recognizes_attribution_and_ignores_documented_examples() {
        let footer = "🤖 Generated with [Claude Code](https://claude.com/claude-code)";
        assert!(has_harness_footer(footer));
        assert!(has_harness_footer("Made with [Cursor](https://cursor.com)"));
        assert!(has_harness_footer(
            "why\n\nCo-Authored-By: Claude <noreply@anthropic.com>"
        ));
        assert!(has_harness_footer(
            "[Claude Code](https://claude.com/claude-code)"
        ));
        assert!(!has_harness_footer(
            "Read [Claude Code](https://claude.com/claude-code)"
        ));
        assert!(!has_harness_footer(
            "Co-authored-by: Claude Monet <claude@example.test>"
        ));
        assert!(!has_harness_footer(
            "Co-Authored-By: Example Person <person@cursor.com>"
        ));
        for doc in [
            format!("> {footer}"),
            format!("    {footer}"),
            format!("~~~~md\n{footer}\n~~~~"),
            format!("{footer}\n\nHere is the actual answer."),
        ] {
            assert!(!has_harness_footer(&doc));
        }
    }
}
